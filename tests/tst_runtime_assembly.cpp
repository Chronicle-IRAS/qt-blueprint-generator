QByteArray read(const QString &path) { QFile file(path); return file.open(QIODevice::ReadOnly) ? file.readAll() : QByteArray{}; }
bool write(const QString &path, const QByteArray &bytes) {
    QFile file(path); return file.open(QIODevice::WriteOnly) && file.write(bytes) == bytes.size();
}
BlueprintDocument blueprint() {
    return *BlueprintSerializer::fromJson(read(QString::fromUtf8(RUNTIME_FIXTURE_DIR) + "/blueprint.json"));
}
QMap<QString, QByteArray> snapshot(const QString &path) {
    QMap<QString, QByteArray> files;
    QDirIterator it(path, QDir::Files | QDir::Hidden | QDir::System, QDirIterator::Subdirectories);
    while (it.hasNext()) { const auto file = it.next(); files[QDir(path).relativeFilePath(file)] = read(file); }
    return files;
}
