    void unsupportedFlowAndPorts() {
        QFETCH(QString, mutation); auto d = blueprint();
        if (mutation == "decision") d.nodes[1].type = NodeType::Decision;
        if (mutation == "external") d.nodes[1].type = NodeType::ExternalCode;
        if (mutation == "branch") d.edges.append({"extra", "z_first", "page", {}});
        if (mutation == "merge") d.edges.append({"extra", "start", "a_second", {}});
        if (mutation == "cycle") d.edges.append({"extra", "a_second", "z_first", {}});
        if (mutation == "multiple-start") d.nodes.append({"another-start", NodeType::Start});
        if (mutation == "multiple-end") d.nodes.append({"another-end", NodeType::End});
        if (mutation == "disconnected") d.nodes.append({"unused", NodeType::LogicModule, "Unused", "Unused logic"});
        if (mutation == "nonterminal-ui") { d.nodes[1].type = NodeType::UiPage; d.nodes[1].outputs.clear(); }
        if (mutation == "multiple-ui") { d.nodes[2].type = NodeType::UiPage; d.nodes[2].outputs.clear(); }
        if (mutation == "label") d.edges[0].label = " ";
        if (mutation == "first-input") d.nodes[1].inputs = {{"message", "QString", {}}};
        if (mutation == "missing-input") d.nodes[2].inputs[0].name = "absent";
        if (mutation == "wrong-type") d.nodes[2].inputs[0].type = "QVariant";
        if (mutation == "start-port") d.nodes[0].outputs = {{"message", "QString", {}}};
        if (mutation == "end-port") d.nodes[4].inputs = {{"message", "QString", {}}};
        if (mutation == "ui-output") d.nodes[3].outputs = {{"message", "QString", {}}};
        if (mutation == "empty-port") d.nodes[1].outputs[0].name.clear();
        if (mutation == "duplicate-port") d.nodes[1].outputs.append(d.nodes[1].outputs[0]);
        if (mutation == "unknown-type") d.nodes[1].outputs[0].type = "CustomType";
        if (mutation == "injected-type") d.nodes[1].outputs[0].type = "QString); system(\"bad\")";
        if (mutation == "unpaired-surrogate") d.nodes[1].outputs[0].name = QString(QChar(0xd800));
        QTemporaryDir dir; QString error; const auto before = snapshot(dir.path());
        QVERIFY(!ProjectScaffolder::createRuntime(d, dir.path(), &error));
        QVERIFY2(!error.isEmpty(), qPrintable(mutation)); QCOMPARE(snapshot(dir.path()), before);
    }
    void supportedTypesAndSafeText() {
        auto d = blueprint(); d.nodes[1].outputs.clear(); d.nodes[2].inputs.clear();
        const QString unusual = QString::fromUtf8("中文\"\\\x01" "F\xc2\xa0\xe2\x80\xa8");
        for (const QString &type : {"bool", "int", "double", "QString", "QByteArray", "QStringList", "QVariantList", "QVariantMap", "QVariant"}) {
            const auto port = PortSpec{unusual + type, type, {}};
            d.nodes[1].outputs.append(port); d.nodes[2].inputs.append(port);
        }
        QMap<QString, QByteArray> files; QString error;
        QVERIFY2(RuntimeAssembler::assemble(d, "Blueprint_Runtime_Linear", files, &error), qPrintable(error));
        const auto cpp = files.value("src/runtime/workflow_controller.cpp");
        QVERIFY(cpp.contains(unusual.toUtf8().toHex()));
        QVERIFY(!cpp.contains(unusual.toUtf8()));
    }
    void versionsCannotCrossOrChangeSchema() {
        for (bool runtime : {false, true}) {
            QTemporaryDir dir; QString error;
            QVERIFY(runtime ? ProjectScaffolder::createRuntime(blueprint(), dir.path()) : ProjectScaffolder::create(blueprint(), dir.path()));
            const auto before = snapshot(dir.path());
            QVERIFY(!(runtime ? ProjectScaffolder::create(blueprint(), dir.path(), &error) : ProjectScaffolder::createRuntime(blueprint(), dir.path(), &error)));
            QVERIFY(error.contains("new workspace")); QCOMPARE(snapshot(dir.path()), before);
            auto stored = manifest(dir.path()); stored["version"] = 3;
            QVERIFY(write(dir.filePath("generation-manifest.json"), WorkspaceIo::json(stored)));
            QJsonObject loaded; QVERIFY(!WorkspaceIo::loadManifest(dir.path(), loaded, &error));
            stored["version"] = runtime ? 2 : 1; stored["mode"] = "injected";
            QVERIFY(write(dir.filePath("generation-manifest.json"), WorkspaceIo::json(stored)));
            QVERIFY(!WorkspaceIo::loadManifest(dir.path(), loaded, &error));
        }
    }
    void runtimePromptAndBatchMode() {
        QTemporaryDir dir; QString capturedPrompt;
        GenerationController controller([&](const AiProviderSettings &, QObject *owner) {
            auto *fake = new FakeAiClient(owner); fake->setSuccessfulResponse(response());
            connect(fake, &IAiClient::responseReady, &controller, [fake, &capturedPrompt] { capturedPrompt = fake->requests().last().prompt; });
            return fake;
        });
        QVERIFY(controller.startRuntime(blueprint(), "z_first", dir.path(), {}));
        QTRY_COMPARE(controller.state(), GenerationController::State::Success);
        QCOMPARE(controller.candidateBatch()->mode, ProjectScaffolder::Mode::LinearRuntime);
        QCOMPARE(manifest(dir.path()).value("version").toInt(), 2);
        QVERIFY(capturedPrompt.contains("createModule_073fde743a5b3153(QObject *parent = nullptr)"));
        QVERIFY(capturedPrompt.contains("Define the exact factory"));
        QVERIFY(capturedPrompt.contains("copy"));
        CandidateReviewDialog dialog(blueprint(), dir.path(), controller.candidateBatch()->generationId,
                                     controller.candidateBatch()->result, nullptr, controller.candidateBatch()->mode);
        dialog.findChild<QPushButton *>("acceptCandidateButton")->click();
        QCOMPARE(read(dir.path() + "/generated-project/src/modules/z_first/implementation/value.cpp"), QByteArray("// accepted candidate"));
    }
